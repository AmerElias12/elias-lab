"""Declarative base, the enums the database already defines, and the mixins
that put the ownership columns on every model.

The mixins exist so that `lab_id`, `owner_id` and the timestamps cannot be
forgotten on a new table: you inherit them or you do not get a model. A column
on its own does not stop a leak, though — see scoping.py for the part that
actually applies the filter, and the row-level security policies for the
backstop underneath both.
"""
from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import TYPE_CHECKING

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql as pg
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column, relationship

if TYPE_CHECKING:  # models imports db, so this stays a type-time reference only
    from app.models import Lab, User


class Base(DeclarativeBase):
    """All models hang off this. Naming conventions are set so Alembic produces
    stable constraint names instead of autogenerated ones that churn."""

    metadata = sa.MetaData(
        naming_convention={
            "ix": "%(table_name)s_%(column_0_N_name)s_idx",
            "uq": "%(table_name)s_%(column_0_N_name)s_key",
            "ck": "%(table_name)s_%(constraint_name)s",
            "fk": "%(table_name)s_%(column_0_name)s_fkey",
            "pk": "%(table_name)s_pkey",
        }
    )


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------
# These types are created by docs/eln-schema.sql, so the ORM must not try to
# emit them again: create_type=False. values_callable pins the PostgreSQL
# labels to the enum *values* rather than the member names, which keeps the two
# definitions from drifting apart if a member is ever renamed in Python.
