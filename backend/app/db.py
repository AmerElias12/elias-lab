def pg_enum(py_enum: type[enum.Enum], name: str) -> pg.ENUM:
    return pg.ENUM(
        py_enum,
        name=name,
        create_type=False,
        values_callable=lambda e: [m.value for m in e],
    )


# ---------------------------------------------------------------------------
# Mixins
# ---------------------------------------------------------------------------
# Foreign keys in a mixin go through declared_attr: a ForeignKey object cannot
# be shared between tables, so each subclass needs its own.
class PrimaryKeyMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid(as_uuid=True), primary_key=True, server_default=sa.text("gen_random_uuid()")
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        sa.TIMESTAMP(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.TIMESTAMP(timezone=True), nullable=False, server_default=sa.func.now()
    )


class SoftDeleteMixin:
    """Nothing scientific is hard-deleted: a construct referenced by a two-year-old
    entry has to stay readable."""

    deleted_at: Mapped[datetime | None] = mapped_column(sa.TIMESTAMP(timezone=True))


class LabScopedMixin:
    """Every row belongs to exactly one lab. This is the column every query
    filters on and every RLS policy keys off."""

    @declared_attr
    def lab_id(cls) -> Mapped[uuid.UUID]:
        return mapped_column(
            sa.ForeignKey("lab.id", ondelete="RESTRICT"), nullable=False, index=True
        )

    @declared_attr
    def lab(cls) -> Mapped["Lab"]:
        return relationship("Lab", lazy="raise")


class OwnedMixin:
    """Who is responsible for this record. Nullable on purpose: people leave the
    lab, and their plasmids must not leave with them."""

    @declared_attr
    def owner_id(cls) -> Mapped[uuid.UUID | None]:
        return mapped_column(
            sa.ForeignKey("app_user.id", ondelete="SET NULL"), nullable=True, index=True
        )

    @declared_attr
    def owner(cls) -> Mapped["User | None"]:
        return relationship("User", lazy="raise", foreign_keys=lambda: [cls.owner_id])
